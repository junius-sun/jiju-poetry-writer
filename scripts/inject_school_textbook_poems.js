// ============ 注入逻辑（按 content 去重，与项目既有脚本一致） ============
function process() {
  const dbPath = path.join(__dirname, '../src/data/poetry_db.js');
  const rawCode = fs.readFileSync(dbPath, 'utf-8');

  const jsonStart = rawCode.indexOf('[');
  const jsonEnd = rawCode.lastIndexOf(']') + 1;
  const list = JSON.parse(rawCode.slice(jsonStart, jsonEnd));

  const existingContents = new Set(list.map(item => item.content));

  // 计算 school_ 系列已用最大编号；同时修复历史遗留的重复 id
  let maxSchoolId = 0;
  for (const item of list) {
    const m = /^school_(\d+)$/.exec(item.id || '');
    if (m) maxSchoolId = Math.max(maxSchoolId, parseInt(m[1], 10));
  }
  const seenIds = new Set();
  let repaired = 0;
  for (const item of list) {
    if (seenIds.has(item.id)) {
      maxSchoolId++;
      item.id = `school_${String(maxSchoolId).padStart(3, '0')}`;
      repaired++;
    }
    seenIds.add(item.id);
  }
  if (repaired > 0) console.log(`🔧 修复重复 id ${repaired} 个`);

  let added = 0;
  let skipped = 0;
  let idIndex = maxSchoolId;
  const errors = [];

  for (const poem of POEMS) {
    for (const [content, pattern, rhyme, tags] of poem.lines) {
      // 结构自检
      if (Array.from(content).length !== pattern.length) {
        errors.push(`字数与平仄长度不符: ${content}`);
        continue;
      }
      if (!/^[01]+$/.test(pattern)) {
        errors.push(`平仄pattern非法: ${content}`);
        continue;
      }
      const endTone = rhyme === null ? "仄" : "平";
      if (rhyme === null && pattern[pattern.length - 1] === "1") {
        errors.push(`仄收句尾字标为平: ${content}`);
        continue;
      }
      if (rhyme !== null && pattern[pattern.length - 1] === "0") {
        errors.push(`平收句尾字标为仄: ${content}`);
        continue;
      }

      if (existingContents.has(content)) {
        skipped++;
        continue;
      }
      existingContents.add(content);

      idIndex++;
      list.push({
        id: `school_${String(idIndex).padStart(3, '0')}`,
        content,
        length: Array.from(content).length,
        author: poem.author,
        dynasty: poem.dynasty,
        title: poem.title,
        ping_ze_pattern: pattern,
        end_tone: endTone,
        rhyme_group: rhyme === null ? "仄声" : rhyme,
        tags
      });
      added++;
    }
  }

  if (errors.length > 0) {
    console.error('❌ 语料自检失败，未写入：');
    errors.forEach(e => console.error(`  - ${e}`));
    process.exit(1);
  }

  const code = `/**
 * 古诗集句工程 - 全量【100% 规范平水韵部 + 经典名篇】数据库
 * 包含《静夜思》《早发白帝城》《登鹳雀楼》《春晓》《清明》《山行》《绝句》《江雪》等全量名篇，
 * 并已补齐中小学教材必背名篇（《春夜喜雨》《望岳》《游子吟》《过零丁洋》《白雪歌》等）。
 * 共包含 ${list.length} 条规范名句。
 */

export const POETRY_DATABASE = ${JSON.stringify(list, null, 2)};
`;

  fs.writeFileSync(dbPath, code, 'utf-8');
  console.log(`✅ 注入完成：新增 ${added} 句，跳过已有 ${skipped} 句，数据库总计 ${list.length} 条`);
  console.log(`   覆盖篇目 ${POEMS.length} 篇`);
}

process();
